#!/usr/bin/env bash
# Host-side orchestrator for the Dima 3-server lab (web / api / db). Run from anywhere:
#
#   frontendnet/deploy/deploy-all.sh [certs|up|db|api|seed|web|all]   (default: all)
#
# Phases (each one is idempotent and can be re-run on its own):
#   certs  frontendnet/deploy/make-certs.sh            -> frontendnet/deploy/certs/ (git-ignored)
#   up     vagrant up (honours DIMA_BOX, DIMA_PROVIDER)
#   db     upload backendnode + install-db.sh on db     (MySQL, schema, DML-only app user, ufw, backups)
#   api    upload backendnode + install-api.sh on api   (Node 22, systemd, nginx 443, ufw)
#   seed   production bootstrap (dist/db/bootstrap.js, generated admin/usuario; marker on api; DIMA_RESEED=1 to force)
#   web    publish-web.sh                               (dotnet publish + install-web.sh on web)
#
# Environment:
#   VAGRANT_DOTFILE_PATH  default $HOME/.local/share/dima-vagrant (Vagrant state outside the checkout,
#                         so deleting a worktree never orphans the VMs)
#   DIMA_BOX              Vagrant box (Vagrantfile default debian/bookworm64; this host: cloud-image/ubuntu-24.04)
#   DIMA_PROVIDER         default libvirt (virtualbox on Windows hosts)
#   DIMA_RESEED=1         run the bootstrap again (re-applies the generated credentials and upserts the catalog)
#
# Secrets: backendnode/deploy/.env.deploy (git-ignored by the root rule ".env.*") is generated here with
# random values ONLY if it does not exist (mode 600) and is never printed. Each VM receives only the keys
# it needs. Certificates and secrets are staged in a private temp dir OUTSIDE the repository, uploaded to
# a 0700 directory on the VM and deleted on every exit path. Nothing is written to backendnode/deploy/certs/.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
CERTS="$HERE/certs"
ENV_DEPLOY="$REPO/backendnode/deploy/.env.deploy"
PROVIDER="${DIMA_PROVIDER:-libvirt}"
export VAGRANT_DOTFILE_PATH="${VAGRANT_DOTFILE_PATH:-$HOME/.local/share/dima-vagrant}"
SEED_MARKER=/var/lib/dima-deploy/seeded

cd "$HERE"

log() { printf '\n==> [%s] %s\n' "$(date +%H:%M:%S)" "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

require() {
  local c
  for c in "$@"; do
    command -v "$c" >/dev/null 2>&1 || die "'$c' is required on the host"
  done
}

# ---------------------------------------------------------------------------------------------
# Secrets
# ---------------------------------------------------------------------------------------------
rand_secret() {
  # URL/shell-safe, ~40 random chars, plus a fixed tail so every character class is present
  # (survives a MySQL validate_password MEDIUM policy if the distro package enables it).
  printf '%s-Aa9' "$(openssl rand -base64 30 | tr '+/' '-_' | tr -d '=\n')"
}

# Production bootstrap accounts (AUD-F008-01). Appended to .env.deploy only if missing, never printed, and
# NOT part of any per-VM key allowlist: phase_seed feeds them to the remote process over stdin.
ensure_bootstrap_creds() {
  local k
  for k in ADMIN_EMAIL ADMIN_PASSWORD USER_EMAIL USER_PASSWORD; do
    grep -q "^$k=" "$ENV_DEPLOY" && continue
    (
      umask 077
      case "$k" in
        ADMIN_EMAIL)    printf 'ADMIN_EMAIL=admin@dima.lab\n' ;;
        USER_EMAIL)     printf 'USER_EMAIL=usuario@dima.lab\n' ;;
        *)              printf '%s=%s\n' "$k" "$(rand_secret)" ;;
      esac >> "$ENV_DEPLOY"
    )
  done
}

ensure_secrets() {
  git -C "$REPO" check-ignore -q "$ENV_DEPLOY" \
    || die "$ENV_DEPLOY is not git-ignored; refusing to write secrets there"
  if [[ -f "$ENV_DEPLOY" ]]; then
    chmod 600 "$ENV_DEPLOY"
    ensure_bootstrap_creds
    return 0
  fi
  log "Generating $ENV_DEPLOY (random values, mode 600, not printed)"
  local app_pass
  app_pass="$(rand_secret)"
  (
    umask 077
    {
      printf '# Generated by frontendnet/deploy/deploy-all.sh on %s. NEVER commit this file.\n' "$(date -u +%FT%TZ)"
      printf 'DB_ROOT_PASSWORD=%s\n' "$(rand_secret)"
      printf 'DB_APP_PASSWORD=%s\n' "$app_pass"
      printf 'DB_PASSWORD=%s\n' "$app_pass"
      printf 'JWT_SECRET=%s\n' "$(openssl rand -hex 35)"
      # SCHEMA.sql creates `mercadolibrenode`; the backend scripts default to dima_db (see changelog).
      printf 'DB_DATABASE=mercadolibrenode\n'
      printf 'DB_USER=dima_app\n'
    } > "$ENV_DEPLOY"
  )
  chmod 600 "$ENV_DEPLOY"
  ensure_bootstrap_creds
}

env_value() { # non-secret keys only (DB_DATABASE, DB_USER)
  sed -n "s/^$1=//p" "$ENV_DEPLOY" | tail -n 1
}

# ---------------------------------------------------------------------------------------------
# Remote helpers
# ---------------------------------------------------------------------------------------------
STAGE=""
cleanup() { [[ -n "$STAGE" ]] && rm -rf "$STAGE"; return 0; }
trap cleanup EXIT

# Copies the committed backendnode tree (git archive: no node_modules, .env, logs or uploads) into a
# private temp dir outside the repo and adds the role's secrets (and, for api, its certificates).
stage_backend() {
  local role="$1" keys
  cleanup
  STAGE="$(umask 077; mktemp -d "${TMPDIR:-/tmp}/dima-$role.XXXXXX")"
  if [[ -n "$(git -C "$REPO" status --porcelain -- backendnode)" ]]; then
    echo "WARN: backendnode/ has uncommitted changes; deploying the committed HEAD only." >&2
  fi
  git -C "$REPO" archive --format=tar HEAD backendnode | tar -x -C "$STAGE"
  case "$role" in
    db)  keys='DB_ROOT_PASSWORD|DB_APP_PASSWORD|DB_DATABASE|DB_USER' ;;
    api) keys='DB_PASSWORD|JWT_SECRET|DB_DATABASE|DB_USER' ;;
    *)   die "unknown role $role" ;;
  esac
  (umask 077; grep -E "^($keys)=" "$ENV_DEPLOY" > "$STAGE/backendnode/deploy/.env.deploy")
  if [[ "$role" == "api" ]]; then
    install -d -m 700 "$STAGE/backendnode/deploy/certs"
    install -m 644 "$CERTS/api.dima.lab.crt" "$CERTS/dima-lab-ca.crt" "$STAGE/backendnode/deploy/certs/"
    install -m 600 "$CERTS/api.dima.lab.key" "$STAGE/backendnode/deploy/certs/"
  fi
  tar -C "$STAGE" -czf "$STAGE/backend.tgz" backendnode
}

# Uploads $STAGE/backend.tgz to a 0700 dir on the VM, extracts it as root into a root-only dir and runs
# the given backend installer; the uploaded secrets are removed on every exit path.
run_backend_installer() {
  local vm="$1" script="$2" up="/tmp/dima-upload-$1"
  vagrant ssh "$vm" -c "sudo rm -rf $up && install -d -m 700 $up"
  vagrant upload "$STAGE/backend.tgz" "$up/backend.tgz" "$vm"
  # SSH_CONNECTION is forwarded explicitly (sudo's env_reset drops it) so the installers' "keep the current ssh
  # peer" ufw rule is written and `vagrant ssh` still works after the firewall is enabled.
  vagrant ssh "$vm" -c "sudo SSH_CONNECTION=\"\${SSH_CONNECTION:-}\" bash -c 'set -euo pipefail
    trap \"rm -rf /tmp/dima-backend $up\" EXIT
    rm -rf /tmp/dima-backend && install -d -m 700 /tmp/dima-backend
    tar --no-same-owner -C /tmp/dima-backend -xzf $up/backend.tgz
    bash /tmp/dima-backend/backendnode/deploy/$script'"
}

require_certs() {
  local f
  for f in "$@"; do
    [[ -f "$CERTS/$f" ]] || die "$CERTS/$f missing; run: $0 certs"
  done
}

# ---------------------------------------------------------------------------------------------
# Phases
# ---------------------------------------------------------------------------------------------
phase_certs() {
  require openssl
  log "certs: make-certs.sh -> $CERTS"
  bash "$HERE/make-certs.sh" "$CERTS"
}

phase_up() {
  require vagrant
  mkdir -p "$VAGRANT_DOTFILE_PATH"
  if [[ -d "$HERE/.vagrant/machines" && -z "$(ls -A "$VAGRANT_DOTFILE_PATH")" ]]; then
    echo "WARN: $HERE/.vagrant holds existing Vagrant state but VAGRANT_DOTFILE_PATH=$VAGRANT_DOTFILE_PATH is empty." >&2
    echo "      To keep managing those VMs, move it first: mv '$HERE/.vagrant'/* '$VAGRANT_DOTFILE_PATH'/" >&2
  fi
  log "up: vagrant up --provider=$PROVIDER (box: ${DIMA_BOX:-debian/bookworm64}, state: $VAGRANT_DOTFILE_PATH)"
  vagrant up --provider="$PROVIDER"
}

phase_db() {
  require vagrant git tar
  ensure_secrets
  log "db: install-db.sh on db"
  stage_backend db
  run_backend_installer db install-db.sh
  cleanup

  # Workaround until backendnode/deploy/backup-db.service stops hard-coding DB_DATABASE=dima_db
  # (SCHEMA.sql creates `mercadolibrenode`): point the nightly backup at the real schema.
  local dbname
  dbname="$(env_value DB_DATABASE)"
  if [[ -n "$dbname" && "$dbname" != "dima_db" ]]; then
    [[ "$dbname" =~ ^[A-Za-z0-9_]{1,64}$ ]] || die "invalid DB_DATABASE in $ENV_DEPLOY"
    log "db: backup-db.service drop-in DB_DATABASE=$dbname"
    vagrant ssh db -c "sudo install -d -m 755 /etc/systemd/system/backup-db.service.d \
      && printf '[Service]\nEnvironment=DB_DATABASE=%s\n' '$dbname' | sudo tee /etc/systemd/system/backup-db.service.d/dima-database.conf >/dev/null \
      && sudo systemctl daemon-reload"
  fi
}

phase_api() {
  require vagrant git tar
  ensure_secrets
  require_certs api.dima.lab.crt api.dima.lab.key dima-lab-ca.crt
  log "api: install-api.sh on api"
  stage_backend api
  run_backend_installer api install-api.sh
  cleanup
}

phase_seed() {
  require vagrant
  ensure_secrets
  if [[ "${DIMA_RESEED:-0}" != "1" ]] && vagrant ssh api -c "sudo test -f $SEED_MARKER" >/dev/null 2>&1; then
    log "seed: already bootstrapped ($SEED_MARKER on api); DIMA_RESEED=1 to run again"
    return 0
  fi
  log "seed: production bootstrap on api (generated credentials over stdin; roles, catalog, admin + usuario)"
  # The credentials travel on the ssh stdin only: they never appear in argv/ps or in the output. The remote
  # shell (running as backendnode) reads them, exports them and execs node with the production env file.
  {
    for k in ADMIN_EMAIL ADMIN_PASSWORD USER_EMAIL USER_PASSWORD; do
      sed -n "s/^$k=//p" "$ENV_DEPLOY" | tail -n 1
    done
  } | vagrant ssh api -c "cd /opt/backendnode && sudo -u backendnode bash -c 'IFS= read -r ADMIN_EMAIL; IFS= read -r ADMIN_PASSWORD; IFS= read -r USER_EMAIL; IFS= read -r USER_PASSWORD; export ADMIN_EMAIL ADMIN_PASSWORD USER_EMAIL USER_PASSWORD; exec node --env-file=/etc/backendnode/backendnode.env /opt/backendnode/dist/db/bootstrap.js' \
    && sudo install -d -m 700 $(dirname "$SEED_MARKER") && sudo touch $SEED_MARKER"
  log "seed: credentials are in $ENV_DEPLOY (mode 600, git-ignored)"
}

phase_web() {
  require vagrant dotnet tar
  require_certs web.dima.lab.crt web.dima.lab.key dima-lab-ca.crt
  log "web: publish-web.sh"
  bash "$HERE/publish-web.sh"
}

usage() {
  echo "Usage: $0 [certs|up|db|api|seed|web|all]" >&2
  exit 2
}

PHASE="${1:-all}"
case "$PHASE" in
  certs) phase_certs ;;
  up)    phase_up ;;
  db)    phase_db ;;
  api)   phase_api ;;
  seed)  phase_seed ;;
  web)   phase_web ;;
  all)   phase_certs; phase_up; phase_db; phase_api; phase_seed; phase_web ;;
  -h|--help) usage ;;
  *) usage ;;
esac

log "phase '$PHASE' done"
if [[ "$PHASE" == "all" || "$PHASE" == "web" ]]; then
  cat <<'EOF'

Host steps that need you (once):
  printf '10.10.10.10 web.dima.lab\n' | sudo tee -a /etc/hosts
  Browser: import frontendnet/deploy/certs/dima-lab-ca.crt as a trusted Authority (see DEPLOY-PLAN.md).
Then open https://web.dima.lab
EOF
fi
